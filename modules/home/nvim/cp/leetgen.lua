---Find the open leetcode.nvim question whose buffer this is.
---@param buf integer
---@return table|nil question
local function open_question(buf)
  if not _G._Lc_state or not _Lc_state.questions then
    return nil
  end
  for _, q in ipairs(_Lc_state.questions) do
    if q.bufnr == buf then
      return q
    end
  end
  return nil
end

---Fetch metaData + sample testcases from the API. Only used when the question
---is not open in leetcode.nvim. Cached on disk; needs no authentication.
---@param slug string
---@param cb fun(meta: table|nil, testcases: string|nil, content: string|nil, err: string|nil)
local function fetch(slug, cb)
  vim.fn.mkdir(CACHE, "p")
  local path = CACHE .. "/" .. slug .. ".json"

  local function deliver(raw)
    local ok, q = pcall(vim.json.decode, raw)
    -- `content` is required: a cache entry written before it was added to the
    -- query would silently yield no expected outputs, so treat it as stale.
    if not ok or not q or not q.metaData or not q.content then
      return false
    end
    local ok2, meta = pcall(vim.json.decode, q.metaData)
    if not ok2 then
      return false
    end
    cb(meta, q.exampleTestcases, q.content)
    return true
  end

  local fd = io.open(path, "r")
  if fd then
    local raw = fd:read("*a")
    fd:close()
    if deliver(raw) then
      return
    end
  end

  local query = "query q($titleSlug: String!){question(titleSlug:$titleSlug)" .. "{metaData exampleTestcases content}}"
  -- curl-impersonate (from Nix): LeetCode fronts some endpoints with bot
  -- protection that rejects a stock curl TLS fingerprint.
  local curl = vim.g.cp_curl or "curl"

  vim.system({
    curl,
    "-s",
    "--max-time",
    "20",
    "https://leetcode.com/graphql",
    "-H",
    "Content-Type: application/json",
    "-H",
    "Referer: https://leetcode.com/problems/" .. slug .. "/",
    "-d",
    vim.json.encode({ query = query, variables = { titleSlug = slug } }),
  }, { text = true }, function(res)
    vim.schedule(function()
      if res.code ~= 0 then
        return cb(nil, nil, nil, "curl failed: " .. tostring(res.stderr or res.code))
      end
      local ok, decoded = pcall(vim.json.decode, res.stdout or "")
      local q = ok and decoded and decoded.data and decoded.data.question
      if not q or not q.metaData then
        return cb(nil, nil, nil, ("no metaData for '%s' (premium-only?)"):format(slug))
      end
      local w = io.open(path, "w")
      if w then
        w:write(vim.json.encode(q))
        w:close()
      end
      if not deliver(vim.json.encode(q)) then
        cb(nil, nil, nil, "could not decode metaData")
      end
    end)
  end)
end

---Reader expression for one parameter of the given LeetCode type.
---@param leet_type string
---@param src string expression yielding the raw text for this argument
---@return string|nil cpp_type
---@return string|nil reader
local function reader_for(leet_type, src)
  local c = cpp_type(leet_type)
  if not c then
    return nil, nil
  end
  if c == "ListNode*" then
    return c, ("_lc::buildList(%s)"):format(src)
  end
  if c == "TreeNode*" then
    return c, ("_lc::buildTree(%s)"):format(src)
  end
  return c, nil -- parsed generically by the caller
end

---Harness for an ordinary single-method problem.
---@param meta table
---@return string|nil body
---@return string|nil err
local function gen_function(meta)
  local decls, args = {}, {}
  for _, prm in ipairs(meta.params) do
    local c, node = reader_for(prm.type, "_lc::line()")
    if not c then
      return nil, ("unsupported parameter type '%s' (%s)"):format(prm.type, prm.name)
    end
    if node then
      table.insert(decls, ("    %s %s = %s;"):format(c, prm.name, node))
    else
      table.insert(decls, ("    %s %s = _lc::read<%s>();"):format(c, prm.name, c))
    end
    table.insert(args, prm.name)
  end

  local rt = cpp_type((meta["return"] or {}).type or "void")
  if not rt then
    return nil, ("unsupported return type '%s'"):format(tostring((meta["return"] or {}).type))
  end

  local call
  if rt == "void" then
    call = ("    s.%s(%s);"):format(meta.name, table.concat(args, ", "))
  else
    call = ("    auto ans = s.%s(%s);\n    _lc::out(ans);\n    cout << '\\n';"):format(
      meta.name,
      table.concat(args, ", ")
    )
  end

  return table.concat({
    "int main() {",
    "    ios::sync_with_stdio(false);",
    "    cin.tie(nullptr);",
    table.concat(decls, "\n"),
    "    Solution s;",
    call,
    "    return 0;",
    "}",
  }, "\n")
end

---Harness for a "design" problem: a class plus a sequence of method calls.
---
---LeetCode feeds these as two lines --
---  ["LRUCache","put","get"]      the call sequence
---  [[2],[1,1],[1]]               the arguments for each call
---and expects [null,null,1] back, with `null` for constructor and void calls.
---@param meta table
---@return string|nil body
---@return string|nil err
local function gen_design(meta)
  local cls = meta.classname
  if not cls then
    return nil, "design problem without a classname"
  end

  -- One dispatch branch per method, plus the constructor.
  local branches = {}

  local ctor_args, ctor_decls = {}, {}
  for i, prm in ipairs((meta.constructor or {}).params or {}) do
    local c = cpp_type(prm.type)
    if not c then
      return nil, ("unsupported constructor param '%s'"):format(prm.type)
    end
    table.insert(ctor_decls, ("            auto %s = _lc::arg<%s>(a, %d);"):format(prm.name, c, i - 1))
    table.insert(ctor_args, prm.name)
  end
  -- Join only the non-empty pieces: a method with no parameters contributes
  -- an empty decls string, which would otherwise leave a blank line.
  local function join(parts)
    return table.concat(
      vim.tbl_filter(function(x)
        return x ~= nil and x ~= ""
      end, parts),
      "\n"
    )
  end

  table.insert(
    branches,
    join({
      ('        if (name == "%s") {'):format(cls),
      table.concat(ctor_decls, "\n"),
      ("            obj = make_unique<%s>(%s);"):format(cls, table.concat(ctor_args, ", ")),
      '            res.push_back("null");',
      "        }",
    })
  )

  for _, m in ipairs(meta.methods or {}) do
    local decls, args = {}, {}
    for i, prm in ipairs(m.params or {}) do
      local c = cpp_type(prm.type)
      if not c then
        return nil, ("unsupported param '%s' in %s"):format(prm.type, m.name)
      end
      table.insert(decls, ("            auto %s = _lc::arg<%s>(a, %d);"):format(prm.name, c, i - 1))
      table.insert(args, prm.name)
    end
    local rt = cpp_type((m["return"] or {}).type or "void")
    if not rt then
      return nil, ("unsupported return '%s' in %s"):format(tostring((m["return"] or {}).type), m.name)
    end
    local invoke
    if rt == "void" then
      invoke = ('            obj->%s(%s);\n            res.push_back("null");'):format(m.name, table.concat(args, ", "))
    else
      invoke = ("            res.push_back(_lc::ser(obj->%s(%s)));"):format(m.name, table.concat(args, ", "))
    end
    table.insert(
      branches,
      join({
        ('        else if (name == "%s") {'):format(m.name),
        table.concat(decls, "\n"),
        invoke,
        "        }",
      })
    )
  end

  return table.concat({
    "int main() {",
    "    ios::sync_with_stdio(false);",
    "    cin.tie(nullptr);",
    "    auto names = _lc::read<vector<string>>();",
    "    auto calls = _lc::groups(_lc::line());",
    ("    unique_ptr<%s> obj;"):format(cls),
    "    vector<string> res;",
    "    for (size_t i = 0; i < names.size(); ++i) {",
    "        const string& name = names[i];",
    "        vector<string> a = i < calls.size() ? _lc::groups(calls[i]) : vector<string>{};",
    table.concat(branches, "\n"),
    "    }",
    "    cout << '[';",
    "    for (size_t i = 0; i < res.size(); ++i) { if (i) cout << ','; cout << res[i]; }",
    '    cout << "]\\n";',
    "    return 0;",
    "}",
  }, "\n")
end

---Build the harness source from metaData.
---@param meta table
---@param buf integer buffer, so already-defined node structs are not duplicated
---@return string|nil source
---@return string|nil err
local function generate(meta, buf)
  local body, err
  if meta.classname or meta.methods then
    body, err = gen_design(meta)
  elseif meta.name and meta.params then
    body, err = gen_function(meta)
  else
    return nil, "unrecognised metaData shape"
  end
  if not body then
    return nil, err
  end

  -- Which node types this problem involves at all.
  local used = nodes_used(meta)
  -- The struct definitions are NOT emitted here. `class Solution` appears
  -- above this block and references TreeNode*/ListNode*, so a definition at
  -- the bottom is too late. They are spliced in above the class instead --
  -- see M.harness.
  local defs = {}

  -- The whole generated tail is now four lines plus main(): the parser,
  -- printer and node builders all live in the shared header.
  local parts = {
    HARNESS_MARK_BEGIN,
    "#ifdef LOCAL",
    body,
    "#endif",
    HARNESS_MARK_END,
  }
  return table.concat(parts, "\n"), nil, used
end

-- Node structs must be visible to `class Solution`, which sits above the
-- generated harness. They go near the top of the file instead, wrapped in
-- `#ifdef LOCAL` so LeetCode's judge (which defines its own) never sees them.

---Insert (or refresh) the leetgen include above `class Solution`.
---
---It must sit above the class, because the class signature can mention
---ListNode*/TreeNode*. Wrapped in `#ifdef LOCAL` so LeetCode's judge (which
---declares its own node types) never sees it.
---
---If the buffer already declares the structs -- LeetCode ships them commented
---out and you may have uncommented them -- LEETGEN_HAVE_NODES suppresses the
---header's copies rather than colliding.
---@param buf integer
local function splice_nodes(buf)
  ensure_header(vim.api.nvim_buf_get_name(buf))

  local lines = vim.api.nvim_buf_get_lines(buf, 0, -1, false)
  local b, e
  for i, l in ipairs(lines) do
    if l:find(NODE_MARK_BEGIN, 1, true) then
      b = i
    elseif b and l:find(NODE_MARK_END, 1, true) then
      e = i
      break
    end
  end
  if b and e then
    vim.api.nvim_buf_set_lines(buf, b - 1, e, false, {})
    lines = vim.api.nvim_buf_get_lines(buf, 0, -1, false)
  end

  local block = { NODE_MARK_BEGIN, "#ifdef LOCAL" }
  if has_struct(buf, "ListNode") or has_struct(buf, "TreeNode") then
    table.insert(block, "#define LEETGEN_HAVE_NODES")
  end
  vim.list_extend(block, { "#include <leetgen.hpp>", "#endif", NODE_MARK_END, "" })

  local at = 0
  for i, l in ipairs(lines) do
    if l:match("^%s*class%s+%w") or l:match("^%s*struct%s+%w") then
      at = i - 1
      break
    end
  end
  vim.api.nvim_buf_set_lines(buf, at, at, false, block)
end

---Replace an existing `#ifdef LOCAL ... #endif` block, or append one.
---@param buf integer
---@param source string
local function splice(buf, source)
  local lines = vim.api.nvim_buf_get_lines(buf, 0, -1, false)
  local first, last

  -- Prefer our own markers. Searching for a bare `#ifdef LOCAL` is not safe
  -- any more: the node-struct block above `class Solution` is also wrapped in
  -- one, and would be matched first.
  for i, l in ipairs(lines) do
    if not first and l:find(HARNESS_MARK_BEGIN, 1, true) then
      first = i
    elseif first and l:find(HARNESS_MARK_END, 1, true) then
      last = i
      break
    end
  end

  -- Fall back to the hand-written stub (`#ifdef LOCAL` with no markers), but
  -- skip the node block by requiring that the region is not marked.
  if not first then
    local in_nodes = false
    for i, l in ipairs(lines) do
      if l:find(NODE_MARK_BEGIN, 1, true) then
        in_nodes = true
      elseif l:find(NODE_MARK_END, 1, true) then
        in_nodes = false
      elseif not in_nodes then
        if not first and l:match("^#ifdef%s+LOCAL") then
          first = i
        elseif first and l:match("^#endif") then
          last = i
          break
        end
      end
    end
  end

  local new = vim.split(source, "\n", { plain = true })
  if first and last then
    vim.api.nvim_buf_set_lines(buf, first - 1, last, false, new)
  else
    table.insert(new, 1, "")
    vim.api.nvim_buf_set_lines(buf, #lines, #lines, false, new)
  end
end

---@param path string
---@param testcases string|nil
local function write_input(path, testcases)
  if not testcases or testcases == "" then
    return
  end
  local w = io.open(vim.fn.fnamemodify(path, ":h") .. "/input.txt", "w")
  if w then
    w:write((testcases:gsub("\n*$", "")) .. "\n")
    w:close()
  end
end

-- Expected outputs ----------------------------------------------------------
--
-- LeetCode's API exposes sample INPUTS (`exampleTestcases`) but not the
-- expected outputs -- those only exist in the prose description, as
-- "<strong>Output:</strong> [1,2]". leetgo scrapes the same place; there is no
-- better source. Parsing is best-effort by nature, so a case whose output
-- cannot be found is simply skipped rather than written with a wrong answer.

---Strip HTML to plain text, decoding the entities LeetCode actually emits.
---@param html string
---@return string
local function untag(html)
  local s = html:gsub("<[^>]->", "")
  local ents = {
    ["&nbsp;"] = " ",
    ["&quot;"] = '"',
    ["&#39;"] = "'",
    ["&lt;"] = "<",
    ["&gt;"] = ">",
    ["&amp;"] = "&",
  }
  for k, v in pairs(ents) do
    s = s:gsub(k, v)
  end
  return s
end

---Pull the "Output:" values out of a problem description, in order.
---@param content string|nil
---@return string[]
local function expected_outputs(content)
  if not content or content == "" then
    return {}
  end
  -- LeetCode writes this two different ways:
  --   "Output: [0,1]"                -- most problems, value on the same line
  --   "Output"  /  "[null,null,1]"   -- design problems, value on the NEXT
  --                                     line (the label is its own <strong>)
  -- Handling only the first form silently produced zero testcases for every
  -- design problem.
  local lines = {}
  for line in untag(content):gmatch("[^\n]+") do
    local t = vim.trim(line)
    if t ~= "" then
      lines[#lines + 1] = t
    end
  end

  local out = {}
  for i, line in ipairs(lines) do
    local same = line:match("^Output:%s*(.+)$")
    if same then
      out[#out + 1] = vim.trim(same)
    elseif line:match("^Output:?$") and lines[i + 1] then
      out[#out + 1] = lines[i + 1]
    end
  end
  return out
end

-- Order-insensitive problems.
--
-- Some problems accept ANY valid answer -- a topological order (210), the
-- grouping in Group Anagrams (49), the triples in 3Sum. Comparing against the
-- single expected value in the statement fails a correct solution.
--
-- LeetCode's API does not expose this: judgeType is "large" for every problem
-- and metaData carries only name/params/return. The statement prose is the
-- only signal, so we detect it there and record the result IN the expected
-- file, as a leading sentinel line. That keeps one source of truth, needs no
-- state in the comparator, and lets you flip a wrong guess by editing the
-- file (<leader>ke).
local UNORDERED_MARK = "!unordered"

local ORDER_FREE_PHRASES = {
  "in any order",
  "return any of them",
  "any valid answer",
  "answers?%s+in%s+any%s+order",
}

---Does the statement say the order of the answer does not matter?
---@param content string|nil problem description HTML
---@return boolean
local function is_order_free(content)
  if not content or content == "" then
    return false
  end
  local text = untag(content):lower()
  for _, p in ipairs(ORDER_FREE_PHRASES) do
    if text:find(p) then
      return true
    end
  end
  return false
end

function M.format_expected(output, content)
  return (is_order_free(content) and UNORDERED_MARK .. "\n" or "") .. output
end

---Split `exampleTestcases` into per-case blocks. LeetCode gives one argument
---per line, so a case is exactly #params lines.
---@param testcases string|nil
---@param nparams integer
---@return string[] blocks
local function split_cases(testcases, nparams)
  if not testcases or testcases == "" or nparams < 1 then
    return {}
  end
  local lines = vim.split((testcases:gsub("\n*$", "")), "\n", { plain = true })
  local blocks = {}
  for i = 1, #lines, nparams do
    local chunk = {}
    for j = i, math.min(i + nparams - 1, #lines) do
      chunk[#chunk + 1] = lines[j]
    end
    if #chunk == nparams then
      blocks[#blocks + 1] = table.concat(chunk, "\n")
    end
  end
  return blocks
end

---Write competitest-format testcase files next to the solution, so
---<leader>kr runs every sample locally and diffs actual vs expected.
---competitest looks for `<dir>/testcases/<fnoext>_input<N>.txt` and
---`..._output<N>.txt` (see testcases_input_file_format in its config).
---@param path string solution file path
---@param testcases string|nil raw exampleTestcases
---@param content string|nil problem description HTML
---@param nparams integer
---@param unordered boolean prefix expected files with the sentinel
---@return integer written number of complete input/output pairs
local function write_competitest(path, testcases, content, nparams, unordered)
  local inputs = split_cases(testcases, nparams)
  local outputs = expected_outputs(content)
  if #inputs == 0 then
    return 0
  end

  local written = 0
  for i, input in ipairs(inputs) do
    local expected = outputs[i]
    if expected then
      require("cp.cases").store(path, input, (unordered and (UNORDERED_MARK .. "\n") or "") .. expected)
      written = written + 1
    end
  end
  return written
end

---Generate the harness for the current buffer and write input.txt beside it.
---@param opts? { preserve_cases?: boolean, on_ready?: fun() }
function M.harness(opts)
  opts = opts or {}
  local buf = vim.api.nvim_get_current_buf()
  local path = vim.api.nvim_buf_get_name(buf)
  if path == "" then
    return vim.notify("Buffer has no file", vim.log.levels.ERROR)
  end
  if vim.bo[buf].filetype ~= "cpp" then
    return vim.notify("Harness generation is C++ only", vim.log.levels.WARN)
  end

  local function apply(meta, testcases, content, source_label)
    local source, err, used = generate(meta, buf)
    if not source then
      return vim.notify("No harness generated: " .. err .. "\nYour manual stub is untouched.", vim.log.levels.WARN)
    end
    -- Structs first (above the class), then the harness at the bottom.
    splice_nodes(buf)
    splice(buf, source)
    -- Save: the compilers (both <leader>rr and competitest) read the file
    -- from disk, so an unsaved buffer would build the previous version --
    -- which for a fresh problem means "undefined symbol _main".
    if vim.bo[buf].modifiable and not vim.bo[buf].readonly then
      vim.api.nvim_buf_call(buf, function()
        vim.cmd("silent write")
      end)
    end
    if not opts.preserve_cases then
      write_input(path, testcases)
    end

    -- Lines per testcase. A plain problem gives one line per parameter; a
    -- design problem always gives exactly two (the call list, then the
    -- argument list), and has no top-level `params` at all -- computing it
    -- from #meta.params yielded 0 and silently wrote no testcases.
    local per_case = (meta.classname or meta.methods) and 2 or #(meta.params or {})
    local unordered = is_order_free(content)
    local cases = 0
    if not opts.preserve_cases then
      cases = write_competitest(path, testcases, content, per_case, unordered)
    end
    local msg = ("Harness ready: %s (%s)"):format(meta.name, source_label)
    if cases > 0 then
      msg = msg .. ("\n%d testcase%s written -- <leader>kr to run and diff"):format(cases, cases == 1 and "" or "s")
    elseif not opts.preserve_cases then
      msg = msg .. "\nNo expected outputs found; input.txt only (<leader>rr)"
    end
    vim.notify(msg, vim.log.levels.INFO)
    if opts.on_ready then
      opts.on_ready()
    end
  end

  -- Preferred path: the question is open, so everything is already in memory
  -- and the testcase buffer includes any cases you added yourself.
  local q = open_question(buf)
  if q and q.q and q.q.meta_data then
    local testcases
    local ok, live = pcall(function()
      return q.console.testcase:content()
    end)
    if ok then
      testcases = live
    end
    return apply(q.q.meta_data, testcases, q.q.content, "from open question")
  end

  local slug = slug_of(path)
  if not slug then
    return vim.notify("Not a leetcode.nvim file (expected '<id>.<slug>.cpp')", vim.log.levels.ERROR)
  end

  vim.notify("Fetching " .. slug .. "...", vim.log.levels.INFO)
  fetch(slug, function(meta, testcases, content, err)
    if not meta then
      return vim.notify(err or "fetch failed", vim.log.levels.ERROR)
    end
    apply(meta, testcases, content, "from API")
  end)
end

---Run the current LeetCode solution against its sample testcases LOCALLY.
---
---`Leet run` uploads your source to LeetCode, compiles it there and polls
---their judge queue -- that is what the "Pending…" spinner is. This instead
---compiles here (ASan/UBSan, precompiled headers) and diffs every sample in
---competitest's grid, which shows pass/fail and actual-vs-expected per case.
---
---Generates the harness and testcases first if they are missing, so a fresh
---problem is still one keystroke.
function M.run_local()
  local buf = vim.api.nvim_get_current_buf()
  local path = vim.api.nvim_buf_get_name(buf)
  if path == "" or vim.bo[buf].filetype ~= "cpp" then
    return vim.notify("Not a C++ solution buffer", vim.log.levels.WARN)
  end

  local dir = vim.fn.fnamemodify(path, ":h")
  local stem = vim.fn.fnamemodify(path, ":t:r")
  local has_cases = #vim.fn.glob(("%s/testcases/%s_input*.txt"):format(dir, stem), false, true) > 0
  local lines = vim.api.nvim_buf_get_lines(buf, 0, -1, false)
  local has_harness = vim.tbl_contains(lines, HARNESS_MARK_BEGIN) and vim.tbl_contains(lines, HARNESS_MARK_END)

  -- competitest is lazy-loaded by lz.n; load it through lz.n so its stub
  -- command is replaced by the real one. Build the sanitized PCH first, so
  -- competitest's compile line picks it up when it is set up.
  local function run_cases()
    if #vim.fn.glob(("%s/testcases/%s_input*.txt"):format(dir, stem), false, true) == 0 then
      return vim.notify("No local testcases available; input.txt only (<leader>rr)", vim.log.levels.WARN)
    end
    local function run()
      vim.api.nvim_buf_call(buf, function()
        require("lz.n").trigger_load("competitest.nvim")
        if vim.fn.exists(":CompetiTest") ~= 2 then
          return vim.notify("competitest.nvim did not load", vim.log.levels.ERROR)
        end
        vim.cmd("CompetiTest run")
      end)
    end
    if package.loaded.competitest then
      return run()
    end
    require("cp.run").pch_ensure(require("cp").paths(require("cp").root(path)), true, run)
  end

  if has_cases and has_harness then
    local has_support = vim.tbl_contains(lines, NODE_MARK_BEGIN)
      and vim.tbl_contains(lines, NODE_MARK_END)
      and vim.tbl_contains(lines, "#include <leetgen.hpp>")
    if not has_support then
      splice_nodes(buf)
    end
    return run_cases()
  end

  -- Testcase files can outlive the generated main(). Wait for generation
  -- itself to finish before compiling, and keep existing custom cases.
  M.harness({ preserve_cases = has_cases, on_ready = run_cases })
end

-- Exposed for testing the codegen without a live buffer or network.
M._test = { generate = generate, cpp_type = cpp_type }

return M

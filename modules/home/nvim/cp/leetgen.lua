---Write the support file for `ft` into the solution's CP root if missing or
---outdated: leetgen.hpp from the source above, leetgen.rs from the copy
---shipped beside this module.
---@param path string solution file
---@param ft "cpp"|"rust"
---@return string support absolute path of the support file
local function ensure_header(path, ft)
  local dir = require("cp").paths(require("cp").root(path)).leetgen
  local support = dir .. (ft == "rust" and "/leetgen.rs" or "/leetgen.hpp")
  local source = HEADER_SRC
  if ft == "rust" then
    source = table.concat(vim.fn.readfile(vim.g.cp_leetgen_rs), "\n") .. "\n"
  end
  local version = function(text)
    return text:match("LEETGEN_VERSION (%d+)")
  end
  vim.fn.mkdir(dir, "p")
  local fd = io.open(support, "r")
  local current = fd and fd:read("*a")
  if fd then
    fd:close()
  end
  if not current or version(current) ~= version(source) then
    local w = assert(io.open(support, "w"))
    w:write(source)
    w:close()
  end
  return support
end

---Is `struct <name>` defined (not commented out) anywhere in the buffer?
---@param buf integer
---@param name string
---@return boolean
local function has_struct(buf, name)
  for _, l in ipairs(vim.api.nvim_buf_get_lines(buf, 0, -1, false)) do
    if l:match("^%s*struct%s+" .. name .. "%s*{") then
      return true
    end
  end
  return false
end


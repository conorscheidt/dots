namespace _lc {
using namespace std;

struct P {
    const string& s;
    size_t i = 0;
    explicit P(const string& src) : s(src) {}
    void ws() { while (i < s.size() && isspace((unsigned char)s[i])) i++; }
    bool peek(char c) { ws(); return i < s.size() && s[i] == c; }
    bool eat(char c) { ws(); if (i < s.size() && s[i] == c) { i++; return true; } return false; }
    // A quoted string (with escapes) or a bare token up to , or ].
    string token() {
        ws();
        string o;
        if (i < s.size() && s[i] == '"') {
            i++;
            while (i < s.size() && s[i] != '"') {
                if (s[i] == '\\' && i + 1 < s.size()) {
                    i++;
                    char c = s[i++];
                    o += (c == 'n' ? '\n' : c == 't' ? '\t' : c);
                } else o += s[i++];
            }
            if (i < s.size()) i++;  // closing quote
            return o;
        }
        while (i < s.size() && s[i] != ',' && s[i] != ']') o += s[i++];
        while (!o.empty() && isspace((unsigned char)o.back())) o.pop_back();
        return o;
    }
};

inline void parse(P& p, int& v)       { string t = p.token(); v = t.empty() ? 0 : stoi(t); }
inline void parse(P& p, long long& v) { string t = p.token(); v = t.empty() ? 0 : stoll(t); }
inline void parse(P& p, double& v)    { string t = p.token(); v = t.empty() ? 0 : stod(t); }
inline void parse(P& p, bool& v)      { v = p.token() == "true"; }
inline void parse(P& p, string& v)    { v = p.token(); }
inline void parse(P& p, char& v)      { string t = p.token(); v = t.empty() ? '\0' : t[0]; }

template <class T> inline void parse(P& p, vector<T>& v) {
    v.clear();
    if (!p.eat('[')) return;      // tolerate a bare scalar where an array was expected
    if (p.eat(']')) return;       // []
    do { T x{}; parse(p, x); v.push_back(x); } while (p.eat(','));
    p.eat(']');
}

// One raw input line. LeetCode gives one argument per line.
inline string line() {
    string l;
    getline(cin, l);
    return l;
}

// One argument per line, matching LeetCode's own testcase format.
template <class T> inline T read() {
    string l;
    getline(cin, l);
    P p(l);
    T v{};
    parse(p, v);
    return v;
}

// Top-level elements of a bracketed list, as raw strings (preserves `null`
// and nested brackets). Used for TreeNode levels and design-problem args.
inline vector<string> groups(const string& line) {
    vector<string> out;
    size_t a = line.find('['), b = line.rfind(']');
    if (a == string::npos || b == string::npos || b <= a) return out;
    string s = line.substr(a + 1, b - a - 1);
    int depth = 0; bool q = false; string cur;
    for (size_t i = 0; i < s.size(); ++i) {
        char c = s[i];
        if (c == '"' && (i == 0 || s[i-1] != '\\')) q = !q;
        if (!q && c == '[') depth++;
        if (!q && c == ']') depth--;
        if (!q && c == ',' && depth == 0) { out.push_back(cur); cur.clear(); continue; }
        cur += c;
    }
    if (!cur.empty()) out.push_back(cur);
    for (auto& t : out) {
        size_t i = t.find_first_not_of(" \t");
        size_t j = t.find_last_not_of(" \t");
        t = (i == string::npos) ? "" : t.substr(i, j - i + 1);
    }
    return out;
}

// Printing, in LeetCode's output format.
inline void out(bool v)          { cout << (v ? "true" : "false"); }
inline void out(char v)          { cout << '"' << v << '"'; }
inline void out(const string& v) {
    cout << '"';
    for (char c : v) {
        if (c == '"' || c == '\\') cout << '\\';
        cout << c;
    }
    cout << '"';
}
inline void out(int v)           { cout << v; }
inline void out(long long v)     { cout << v; }
inline void out(double v)        { cout << v; }
template <class T> inline void out(const vector<T>& v) {
    cout << '[';
    for (size_t i = 0; i < v.size(); ++i) { if (i) cout << ','; out(v[i]); }
    cout << ']';
}

// Capture any out() as a string, for design problems that accumulate results.
template <class T> inline string ser(const T& v) {
    ostringstream ss;
    auto* old = cout.rdbuf(ss.rdbuf());
    out(v);
    cout.rdbuf(old);
    return ss.str();
}

// Parse one argument out of a design-problem parameter group, by index.
template <class T> inline T arg(const vector<string>& parts, size_t i) {
    T v{};
    if (i < parts.size()) { P p(parts[i]); parse(p, v); }
    return v;
}

// Lists serialise as [1,2,3]. Serialisation formats are LeetCode's own;
// written from the spec, though the approach follows leetgo (MIT, j178/leetgo).
// Nodes are leaked deliberately: the process is about to exit, and freeing
// them would only add noise under ASan.
inline ListNode* buildList(const string& line) {
    P p(line);
    vector<int> v;
    parse(p, v);
    ListNode head(0);
    ListNode* cur = &head;
    for (int x : v) { cur->next = new ListNode(x); cur = cur->next; }
    return head.next;
}
// Lets the generic vector<T> parser handle ListNode[] (problem 23, "Merge k
// Sorted Lists", where the input is [[1,4,5],[1,3,4],[2,6]] -- an array OF
// lists). Found at instantiation via ADL: the first parameter is _lc::P, so
// _lc is an associated namespace even though this is declared after the
// vector template.
inline void parse(P& p, ListNode*& v) {
    vector<int> xs;
    parse(p, xs);
    ListNode head(0);
    ListNode* cur = &head;
    for (int x : xs) { cur->next = new ListNode(x); cur = cur->next; }
    v = head.next;
}

inline void out(ListNode* h) {
    cout << '[';
    for (bool first = true; h; h = h->next, first = false) { if (!first) cout << ','; cout << h->val; }
    cout << ']';
}

inline TreeNode* buildTree(const string& line) {
    vector<string> t = groups(line);
    if (t.empty() || t[0] == "null" || t[0].empty()) return nullptr;
    TreeNode* root = new TreeNode(stoi(t[0]));
    queue<TreeNode*> q;
    q.push(root);
    size_t i = 1;
    while (!q.empty() && i < t.size()) {
        TreeNode* n = q.front();
        q.pop();
        if (i < t.size()) { if (t[i] != "null") { n->left  = new TreeNode(stoi(t[i])); q.push(n->left);  } i++; }
        if (i < t.size()) { if (t[i] != "null") { n->right = new TreeNode(stoi(t[i])); q.push(n->right); } i++; }
    }
    return root;
}
inline void out(TreeNode* r) {
    vector<string> v;
    queue<TreeNode*> q;
    if (r) q.push(r);
    while (!q.empty()) {
        TreeNode* n = q.front();
        q.pop();
        if (!n) { v.push_back("null"); continue; }
        v.push_back(to_string(n->val));
        q.push(n->left);
        q.push(n->right);
    }
    while (!v.empty() && v.back() == "null") v.pop_back();  // LeetCode trims trailing holes
    cout << '[';
    for (size_t i = 0; i < v.size(); ++i) { if (i) cout << ','; cout << v[i]; }
    cout << ']';
}

}  // namespace _lc

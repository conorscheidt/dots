---Is `struct <name>` defined (not commented out) anywhere in the buffer?
---@param buf integer
---@param name string
---@return boolean
local function has_struct(buf, name)
  for _, l in ipairs(vim.api.nvim_buf_get_lines(buf, 0, -1, false)) do
    if l:match("^%s*struct%s+" .. name .. "%s*{") then
      return true
    end
  end
  return false
end

---Which node structs a metaData block references.
---@param meta table
---@return table<string, boolean>
local function nodes_used(meta)
  local used = {}
  local function scan(t)
    if type(t) ~= "table" then
      return
    end
    if type(t.type) == "string" then
      for name in pairs(NODE_DEFS) do
        if t.type:find(name, 1, true) then
          used[name] = true
        end
      end
    end
    for _, v in pairs(t) do
      scan(v)
    end
  end
  scan(meta)
  return used
end


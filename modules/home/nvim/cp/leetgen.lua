-- LeetCode type string -> C++ type. Parsing is handled generically by the
-- emitted `_lc::read<T>()`, so this table only needs the type name.
local TYPES = {
  ["integer"] = "int",
  ["long"] = "long long",
  ["double"] = "double",
  ["boolean"] = "bool",
  ["string"] = "string",
  ["character"] = "char",
  ["void"] = "void",
  -- Pointer types: built by _lc::buildList / _lc::buildTree rather than parsed.
  ["ListNode"] = "ListNode*",
  ["TreeNode"] = "TreeNode*",
}

---LeetCode writes `list<T>` and `T[]` interchangeably, and nests both.
---Resolve either to a C++ type, recursively.
---@param t string
---@return string|nil
local function cpp_type(t)
  t = vim.trim(t or "")
  local inner = t:match("^list<(.+)>$")
  if inner then
    local c = cpp_type(inner)
    return c and ("vector<" .. c .. ">") or nil
  end
  if t:sub(-2) == "[]" then
    local c = cpp_type(t:sub(1, -3))
    return c and ("vector<" .. c .. ">") or nil
  end
  return TYPES[t]
end


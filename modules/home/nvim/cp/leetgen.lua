---Write the header into the solution's CP root if missing or outdated.
---@param path string solution file
local function ensure_header(path)
  local dir = require("cp").paths(require("cp").root(path)).leetgen
  local header = dir .. "/leetgen.hpp"
  vim.fn.mkdir(dir, "p")
  local fd = io.open(header, "r")
  if fd then
    local cur = fd:read("*a")
    fd:close()
    local v = tonumber(cur:match("LEETGEN_VERSION (%d+)") or "0")
    if v == HEADER_VERSION then
      return
    end
  end
  local w = io.open(header, "w")
  if w then
    w:write(HEADER_SRC)
    w:close()
  end
end

